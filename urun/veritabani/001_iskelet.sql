DO $$ DECLARE s text; BEGIN
  IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='irp_sahibi') THEN CREATE ROLE irp_sahibi NOLOGIN; END IF;
  EXECUTE format('GRANT irp_sahibi TO %I', current_user);
  FOREACH s IN ARRAY ARRAY['irp','motor','saat','kg','gorev','ana_veri','kapi','takvim','k6','k7','k9','k10','k10_1','k10_2','is_','liste','surum','zaman','yetki_v6','yasam_v5','kapilar_v3','kapilar_v5','maliyet_izi_v6'] LOOP
    EXECUTE format('CREATE SCHEMA IF NOT EXISTS %I AUTHORIZATION irp_sahibi',s);
    EXECUTE format('REVOKE ALL ON SCHEMA %I FROM PUBLIC',s);
  END LOOP;
END $$;
GRANT USAGE ON SCHEMA auth TO irp_sahibi;
